/**
 * Спостерігач (Observer). Отримує сповіщення про кожен прочитаний рядок
 * та про завершення читання файлу.
 */
public interface LineObserver {
    /** Викликається на кожен прочитаний рядок. */
    void onLine(String line);

    /** Викликається після завершення читання — час вивести результат. */
    void onComplete();
}
