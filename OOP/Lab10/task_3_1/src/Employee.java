/**
 * Компонент (Component) шаблону Компонувальник.
 * Єдиний інтерфейс і для окремого співробітника (лист),
 * і для відділу (композит). Клієнт працює з усіма однаково.
 */
public interface Employee {
    /** Виплатити зарплату (собі та всім підлеглим, якщо це відділ). */
    void payExpenses();

    /** Сумарний фонд оплати (для перевірки/звіту). */
    int totalSalary();
}
